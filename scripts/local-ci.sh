    rm -rf "$run_root" 2>/dev/null || docker run --rm \
      -v "$state_root:/state" "$alpine_image" \
      rm -rf "/state/work/$run_id" >/dev/null
  fi
  rm -rf "$lock_dir" >/dev/null 2>&1 || true
}

project_image_refs() {
  docker image ls --format '{{.Repository}}:{{.Tag}}' \
    | grep '^jilinjobs-cms-local/' \
