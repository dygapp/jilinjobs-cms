remove_container() { docker rm -f "$1" >/dev/null 2>&1 || true; }

write_buildkit_config() {
  local mirrors_json
  mirrors_json="$(docker info --format '{{json .RegistryConfig.Mirrors}}')"
  python3 - "$buildkit_config" "$mirrors_json" <<'PY'
import json
import pathlib
import sys
from urllib.parse import urlparse

path = pathlib.Path(sys.argv[1])
mirrors = []
for raw in json.loads(sys.argv[2] or "[]"):
    parsed = urlparse(raw)
    value = (parsed.netloc + parsed.path).rstrip("/") if parsed.scheme else raw.rstrip("/")
    if value and value not in mirrors:
        mirrors.append(value)

lines = [
    "# Generated by scripts/local-ci.sh from the host Docker daemon registry mirrors.",
    "# Local execution state only; do not commit this file.",
]
if mirrors:
    lines += [
        '[registry."docker.io"]',
        "  mirrors = [" + ", ".join(json.dumps(item) for item in mirrors) + "]",
    ]
else:
    lines += ["# No host Docker Hub registry mirrors are configured; BuildKit will use Docker Hub directly."]

path.write_text("\n".join(lines) + "\n", encoding="utf-8")
PY
}

ensure_builder() {
  write_buildkit_config
  local desired current
  desired="$(sha256sum "$buildkit_config" | awk '{print $1}')"
  current="$(cat "$builder_config_fingerprint_file" 2>/dev/null || true)"

  if ! docker buildx inspect "$builder" >/dev/null 2>&1 || [[ "$current" != "$desired" ]]; then
    docker buildx rm -f "$builder" >/dev/null 2>&1 || true
    docker buildx create --name "$builder" --driver docker-container \
      --buildkitd-config "$buildkit_config" --bootstrap >/dev/null
    printf '%s\n' "$desired" > "$builder_config_fingerprint_file"
    return
  fi

  docker buildx inspect "$builder" --bootstrap >/dev/null
}

acquire_lock() {
  if mkdir "$lock_dir" 2>/dev/null; then
    printf '%s\n' "$$" > "$lock_dir/pid"
    return
  fi

  local lock_pid=""
  lock_pid="$(cat "$lock_dir/pid" 2>/dev/null || true)"
  if [[ "$lock_pid" =~ ^[0-9]+$ ]] && kill -0 "$lock_pid" 2>/dev/null; then
    die "another local CI run appears active (pid $lock_pid): $lock_dir"
  fi

  rm -rf "$lock_dir" || die "cannot remove stale local CI lock: $lock_dir"
  mkdir "$lock_dir" || die "cannot acquire local CI lock after stale-lock cleanup: $lock_dir"
  printf '%s\n' "$$" > "$lock_dir/pid"
  printf 'Recovered stale local CI lock.\n'
}

cleanup_runtime() {
  remove_container "$backend_container"
  remove_container "$frontend_container"
  remove_container "$mysql_container"
  remove_container cms-backend
  remove_container cms-frontend
  remove_container review-baseline-backend
  remove_container review-baseline-copy
