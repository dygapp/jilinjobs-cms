    printf '\nBuilder cache (%s):\n' "$builder"
    docker buildx du --builder "$builder" 2>/dev/null || printf 'Builder cache is currently inactive; the next build will bootstrap it.\n'
  fi
  if [[ -f "$evidence_root/latest.txt" ]]; then
    printf '\nLatest evidence: %s\n' "$(cat "$evidence_root/latest.txt")"
  fi
}

