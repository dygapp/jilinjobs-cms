mysql_exec() {
  docker exec "$mysql_container" mysql --default-character-set=utf8mb4 -uroot -proot "$@"
}
mysql_query() {
  local database="$1" sql="$2"
  docker exec "$mysql_container" mysql --default-character-set=utf8mb4 \
    -uroot -proot "$database" -N -B -e "$sql"
}
reset_database() {
  local database="$1"
  mysql_exec -e "DROP DATABASE IF EXISTS \`$database\`; CREATE DATABASE \`$database\` CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;"
}

