image_matches() {
  local image="$1" component="$2" fingerprint="$3"
  docker image inspect "$image" >/dev/null 2>&1 \
    && [[ "$(docker image inspect --format '{{ index .Config.Labels "io.jilinjobs.local-ci.component" }}' "$image")" == "$component" ]] \
    && [[ "$(docker image inspect --format '{{ index .Config.Labels "io.jilinjobs.local-ci.input-fingerprint" }}' "$image")" == "$fingerprint" ]]
}
baseline_matches() {
  local image="$1" backend_fp="$2" baseline_fp="$3"
  docker image inspect "$image" >/dev/null 2>&1 \
    && [[ "$(docker image inspect --format '{{ index .Config.Labels "io.jilinjobs.backend-fingerprint" }}' "$image")" == "$backend_fp" ]] \
    && [[ "$(docker image inspect --format '{{ index .Config.Labels "io.jilinjobs.review-baseline-fingerprint" }}' "$image")" == "$baseline_fp" ]]
}
buildx_local_image() {
  local image="$1" component="$2" fingerprint="$3" dockerfile="$4" context="$5"
  if image_matches "$image" "$component" "$fingerprint"; then
    printf 'reuse %s\n' "$image" | tee -a "$evidence_dir/image-reuse.log"
    return
  fi
  docker buildx build --builder "$builder" --load \
    --label io.jilinjobs.local-ci.repository=dygapp/jilinjobs-cms \
    --label "io.jilinjobs.local-ci.component=$component" \
    --label "io.jilinjobs.local-ci.input-fingerprint=$fingerprint" \
    --label "org.opencontainers.image.revision=$head_sha" \
    --label "io.jilinjobs.local-ci.worktree-fingerprint=$worktree_fingerprint" \
    -t "$image" -f "$dockerfile" "$context"
}

