}

clean_project_cache() {
  say "Remove local CI runtime containers"
  cleanup_runtime
  local refs
  refs="$(project_image_refs)"
  if [[ -n "$refs" ]]; then
    printf '%s\n' "$refs" | xargs -r docker image rm -f
  fi
  if docker buildx inspect "$builder" >/dev/null 2>&1; then
    docker buildx prune --builder "$builder" --all --force
  fi
  rm -rf "$state_root"
}

